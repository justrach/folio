/** Translate the SQLite migrations into Postgres DDL.
 *
 * Tables and indexes translate mechanically. Simple triggers (immutability
 * guards, cascade deletes) become plpgsql functions. Anything that needs
 * SQLite-only functions (`iif`, `json_type`, `unixepoch`) is reported rather
 * than guessed at — those are the cost-accounting triggers and need a
 * hand-written port.
 */

import { quoteReserved } from "./compat";

export type TranslatedStatement = {
  sql: string;
  kind: "table" | "index" | "trigger" | "seed" | "skipped";
  note?: string;
};

const UNSUPPORTED = /\b(iif|json_type|json_valid|unixepoch|json_each|json_extract|strftime)\s*\(/i;

function stripComments(raw: string) {
  return raw
    .split("\n")
    .filter(line => !/^\s*--/.test(line))
    .join("\n")
    .trim();
}

function pushStatement(target: string[], raw: string) {
  const cleaned = stripComments(raw);
  if (cleaned) target.push(cleaned);
}

/** Split a migration file on statement boundaries, keeping trigger bodies whole. */
export function splitStatements(sql: string): string[] {
  const statements: string[] = [];
  let current = "";
  let quote: string | null = null;
  for (let index = 0; index < sql.length; index += 1) {
    const char = sql[index];
    // Line comments may contain semicolons; copy them whole and keep scanning.
    if (!quote && char === "-" && sql[index + 1] === "-") {
      const end = sql.indexOf("\n", index);
      const stop = end === -1 ? sql.length : end;
      current += sql.slice(index, stop);
      index = stop - 1;
      continue;
    }
    current += char;
    if (quote) {
      if (char === quote) quote = null;
      continue;
    }
    if (char === "'") {
      quote = "'";
      continue;
    }
    if (char === ";") {
      const trimmed = stripComments(current);
      if (/^CREATE\s+TRIGGER/i.test(trimmed) && !/\bEND\s*;$/i.test(trimmed)) continue;
      if (trimmed) pushStatement(statements, trimmed);
      current = "";
      continue;
    }
  }
  const tail = current.trim();
  if (tail) pushStatement(statements, tail);
  return statements;
}

/** SQLite's `IS`/`IS NOT` compare values (NULL-safe); Postgres spells that
 * DISTINCT FROM. Only the value form is rewritten — `IS NULL`, `IS TRUE`,
 * `IS DISTINCT FROM` keep their meaning. */
function translateIsComparisons(sql: string): string {
  return sql
    .replace(/\bIS\s+NOT\s+(?!NULL\b|TRUE\b|FALSE\b|DISTINCT\b|UNKNOWN\b)/gi, "IS DISTINCT FROM ")
    .replace(/\bIS\s+(?!NOT\b|NULL\b|TRUE\b|FALSE\b|DISTINCT\b|UNKNOWN\b)/gi, "IS NOT DISTINCT FROM ");
}

function translateTypes(sql: string): string {
  return sql
    .replace(/length\(\s*CAST\(([^()]+?)\s+AS\s+BLOB\s*\)\s*\)/gi, "octet_length($1)")
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/\bTEXT\b/g, "text")
    .replace(/\bINTEGER\b/g, "bigint")
    .replace(/\bREAL\b/g, "double precision")
    .replace(/\bBLOB\b/g, "bytea");
}

function translateSimpleTrigger(statement: string): TranslatedStatement {
  const begin = statement.search(/\bBEGIN\b/i);
  if (begin === -1) return { kind: "skipped", sql: statement, note: "trigger without BEGIN" };
  const header = statement.slice(0, begin).trim();
  const body = statement.slice(begin + 5).replace(/\bEND\s*;?\s*$/i, "").trim();
  const parsed = /^CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z0-9_]+)\s+(BEFORE|AFTER)\s+(INSERT|UPDATE|DELETE)(?:\s+OF\s+([A-Za-z0-9_,\s]+?))?\s+ON\s+([A-Za-z0-9_]+)(?:\s+WHEN\s+([\s\S]+))?$/i.exec(header);
  if (!parsed) return { kind: "skipped", sql: statement, note: "trigger header not parsed" };
  const [, name, timing, event, columns, table, when] = parsed;
  if (UNSUPPORTED.test(body) || UNSUPPORTED.test(when ?? "") || /\browid\b/i.test(body))
    return { kind: "skipped", sql: statement, note: `trigger ${name} needs a hand-written port` };

  const raise = /^SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*'([^']*)'\s*\)\s*;?$/i.exec(body);
  const inner = raise
    ? `RAISE EXCEPTION '${raise[1].replace(/'/g, "''")}';`
    : `${translateIsComparisons(body.replace(/;?\s*$/, ";"))}`;
  const returns = event.toUpperCase() === "DELETE" ? "OLD" : "NEW";
  const columnList = columns ? ` OF ${columns.trim()}` : "";
  const whenClause = when ? ` WHEN (${translateIsComparisons(when.trim())})` : "";
  const sql = [
    `CREATE OR REPLACE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $$`,
    `BEGIN`,
    ...inner.split("\n").map(line => `  ${line}`),
    `  RETURN ${returns};`,
    `END $$;`,
    `DROP TRIGGER IF EXISTS ${name} ON ${table};`,
    `CREATE TRIGGER ${name} ${timing.toUpperCase()} ${event.toUpperCase()}${columnList} ON ${table}`,
    `FOR EACH ROW${whenClause} EXECUTE FUNCTION ${name}_fn();`,
  ].join("\n");
  return { kind: "trigger", sql };
}

export function translateStatement(raw: string): TranslatedStatement {
  const statement = raw.trim();
  if (/^PRAGMA\b/i.test(statement)) return { kind: "skipped", sql: statement, note: "PRAGMA has no Postgres equivalent" };
  if (/^CREATE\s+TRIGGER\b/i.test(statement)) return translateSimpleTrigger(statement);

  if (/^CREATE\s+TABLE\b/i.test(statement)) return { kind: "table", sql: quoteReserved(translateTypes(statement)) };
  if (/^CREATE\s+(UNIQUE\s+)?INDEX\b/i.test(statement)) return { kind: "index", sql: quoteReserved(statement) };
  if (/^ALTER\s+TABLE\b/i.test(statement))
    return { kind: "table", sql: quoteReserved(translateTypes(statement)) };
  if (/^DROP\s+TRIGGER\b/i.test(statement))
    return { kind: "skipped", sql: statement, note: "trigger drop is folded into its recreation" };
  if (/^(CREATE|DROP)\s+(OR\s+REPLACE\s+)?VIEW\b/i.test(statement))
    return { kind: "skipped", sql: statement, note: "view needs a hand-written port (rowid / SQLite functions)" };
  if (/^INSERT\s+(OR\s+IGNORE\s+)?INTO\b/i.test(statement) && UNSUPPORTED.test(statement))
    return { kind: "skipped", sql: statement, note: "backfill uses SQLite JSON functions" };
  if (/^INSERT\s+(OR\s+IGNORE\s+)?INTO\b/i.test(statement)) {
    const base = statement.replace(/^INSERT\s+OR\s+IGNORE/i, "INSERT").replace(/;\s*$/, "");
    return { kind: "seed", sql: base.match(/ON\s+CONFLICT/i) ? base : `${base} ON CONFLICT DO NOTHING` };
  }
  return { kind: "skipped", sql: statement, note: "unrecognised statement" };
}

export function translateMigration(source: string): TranslatedStatement[] {
  return splitStatements(source).map(translateStatement);
}

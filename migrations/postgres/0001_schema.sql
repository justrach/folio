-- SQLite-compatible read functions for the *bounded* JSON paths used by D1 callers.
-- JSON strings stay TEXT; missing paths and JSON null return SQL NULL.
CREATE FUNCTION json_extract(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE WHEN jsonb_typeof(doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.')) IN ('object','array')
   THEN (doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.'))::text
   ELSE doc::jsonb #>> string_to_array(trim(leading '$.' FROM path),'.') END
$$;
CREATE FUNCTION json_type(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE jsonb_typeof(doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.'))
 WHEN 'number' THEN CASE WHEN json_extract(doc,path) ~ '^-?[0-9]+$' THEN 'integer' ELSE 'real' END
 WHEN 'boolean' THEN CASE WHEN json_extract(doc,path)='true' THEN 'true' ELSE 'false' END
 ELSE jsonb_typeof(doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.')) END
$$;
CREATE FUNCTION json_each(doc text, path text DEFAULT '$') RETURNS TABLE(value text) LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE WHEN jsonb_typeof(x.v) IN ('array','object') THEN x.v::text ELSE x.v #>> '{}' END
 FROM jsonb_each(CASE WHEN jsonb_typeof(doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.'))='object'
   THEN doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.') ELSE '{}'::jsonb END) x(key,v)
 UNION ALL
 SELECT CASE WHEN jsonb_typeof(y.v) IN ('array','object') THEN y.v::text ELSE y.v #>> '{}' END
 FROM jsonb_array_elements(CASE WHEN jsonb_typeof(doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.'))='array'
   THEN doc::jsonb #> string_to_array(trim(leading '$.' FROM path),'.') ELSE '[]'::jsonb END) y(v)
$$;
-- Supported SQLite form: strftime('%Y-%m-%d', epoch_ms/1000, 'unixepoch').
CREATE FUNCTION strftime(fmt text, epoch_seconds double precision, modifier text) RETURNS text LANGUAGE plpgsql STABLE AS $$
BEGIN
 IF modifier <> 'unixepoch' THEN RAISE EXCEPTION 'Unsupported strftime modifier'; END IF;
 IF fmt = '%Y-%m-%d' THEN RETURN to_char(to_timestamp(epoch_seconds) AT TIME ZONE 'UTC','YYYY-MM-DD'); END IF;
 IF fmt = '%Y-%m' THEN RETURN to_char(to_timestamp(epoch_seconds) AT TIME ZONE 'UTC','YYYY-MM'); END IF;
 IF fmt = '%Y-%m-%dT%H:%M:%fZ' THEN RETURN to_char(to_timestamp(epoch_seconds) AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'); END IF;
 RAISE EXCEPTION 'Unsupported strftime format';
END $$;

CREATE FUNCTION folio_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF current_setting('folio.importing',true)='on' THEN RETURN NEW; END IF;
 IF TG_TABLE_NAME='agent_api_requests' THEN
   IF (to_jsonb(NEW)-'disposition') IS DISTINCT FROM (to_jsonb(OLD)-'disposition')
      OR NOT (OLD.disposition='started' AND NEW.disposition='denied') THEN RAISE EXCEPTION 'API request identities and saved outcomes are immutable'; END IF;
 ELSIF TG_TABLE_NAME IN ('seo_agent_requests','provider_cost_observations') THEN
   RAISE EXCEPTION 'Append-only observation / request';
 ELSIF TG_TABLE_NAME='keyword_benchmark_runs' THEN
   IF ROW(NEW.id,NEW.user_id,NEW.suite_id,NEW.case_id,NEW.kind,NEW.baseline_run_id,NEW.model,
       NEW.harness_version,NEW.environment_type,NEW.environment_fingerprint,NEW.case_json,NEW.created_at,
       NEW.allowed_domains_json,NEW.deadline_at) IS DISTINCT FROM
      ROW(OLD.id,OLD.user_id,OLD.suite_id,OLD.case_id,OLD.kind,OLD.baseline_run_id,OLD.model,
       OLD.harness_version,OLD.environment_type,OLD.environment_fingerprint,OLD.case_json,OLD.created_at,
       OLD.allowed_domains_json,OLD.deadline_at)
      OR (OLD.session_id IS NOT NULL AND NEW.session_id IS DISTINCT FROM OLD.session_id)
      OR (OLD.create_attempt_at IS NOT NULL AND NEW.create_attempt_at IS DISTINCT FROM OLD.create_attempt_at)
      OR (OLD.cancel_attempt_at IS NOT NULL AND NEW.cancel_attempt_at IS DISTINCT FROM OLD.cancel_attempt_at)
      OR (OLD.cancel_acknowledged_at IS NOT NULL AND NEW.cancel_acknowledged_at IS DISTINCT FROM OLD.cancel_acknowledged_at)
      THEN RAISE EXCEPTION 'Benchmark inputs and lifecycle are immutable'; END IF;
   IF NEW.hold_release_at IS DISTINCT FROM OLD.hold_release_at OR NEW.hold_release_reason IS DISTINCT FROM OLD.hold_release_reason THEN
     IF OLD.hold_release_at IS NOT NULL OR OLD.hold_release_reason IS NOT NULL OR NEW.hold_release_at IS NULL
        OR NEW.hold_release_at < OLD.updated_at OR NEW.hold_release_reason IS DISTINCT FROM 'owner-acknowledged-unknown-creation-cost'
        OR OLD.status <> 'requires_action' OR OLD.session_id IS NOT NULL OR OLD.create_attempt_at IS NULL
        OR OLD.answer_json IS NOT NULL OR NEW.status IS DISTINCT FROM OLD.status OR NEW.session_id IS DISTINCT FROM OLD.session_id
        OR NEW.answer_json IS DISTINCT FROM OLD.answer_json OR NEW.usage_json IS DISTINCT FROM OLD.usage_json
        OR NEW.provider_metadata_json IS DISTINCT FROM OLD.provider_metadata_json OR NEW.error IS DISTINCT FROM OLD.error
        OR NEW.revision <> OLD.revision+1 OR NEW.updated_at IS DISTINCT FROM NEW.hold_release_at
     THEN RAISE EXCEPTION 'Hold release acknowledgement is invalid or immutable'; END IF;
   END IF;
   IF NEW.archived_at IS DISTINCT FROM OLD.archived_at THEN
     IF OLD.archived_at IS NOT NULL OR NEW.archived_at IS NULL OR OLD.status <> 'requires_action'
        OR OLD.create_attempt_at IS NULL OR OLD.answer_json IS NOT NULL OR NEW.archived_at < OLD.created_at+86400000
        OR (OLD.session_id IS NOT NULL AND OLD.cancel_attempt_at IS NULL)
        OR NEW.status IS DISTINCT FROM OLD.status OR NEW.session_id IS DISTINCT FROM OLD.session_id
        OR NEW.answer_json IS DISTINCT FROM OLD.answer_json OR NEW.usage_json IS DISTINCT FROM OLD.usage_json
        OR NEW.provider_metadata_json IS DISTINCT FROM OLD.provider_metadata_json OR NEW.error IS DISTINCT FROM OLD.error
        OR NEW.revision <> OLD.revision+1 OR NEW.updated_at IS DISTINCT FROM NEW.archived_at
     THEN RAISE EXCEPTION 'Archive requires an old unresolved attempt and retains accounting'; END IF;
   END IF;
   IF OLD.status IN ('completed','failed','cancelled') AND
     (OLD.session_id IS NULL OR NEW.status IS DISTINCT FROM OLD.status OR NEW.answer_json IS DISTINCT FROM OLD.answer_json
      OR NEW.provider_metadata_json IS DISTINCT FROM OLD.provider_metadata_json OR NEW.error IS DISTINCT FROM OLD.error
      OR NEW.cancel_attempt_at IS DISTINCT FROM OLD.cancel_attempt_at OR NEW.cancel_acknowledged_at IS DISTINCT FROM OLD.cancel_acknowledged_at
      OR NEW.hold_release_at IS DISTINCT FROM OLD.hold_release_at OR NEW.hold_release_reason IS DISTINCT FROM OLD.hold_release_reason
      OR NEW.archived_at IS DISTINCT FROM OLD.archived_at OR NEW.revision <> OLD.revision+1 OR NEW.updated_at < OLD.updated_at
      OR NOT d1_json_valid(NEW.usage_json)) THEN RAISE EXCEPTION 'Terminal benchmark observations are immutable'; END IF;
 END IF;
 RETURN NEW;
END $$;

-- Historical rates belong to the D1 export; do not seed newer prices here.
-- Observations are cumulative snapshots, not chargeable invoices.
CREATE FUNCTION folio_cost_snapshot() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE src text; rev bigint; prov text; mdl text; stat text; inp bigint; cached bigint; outp bigint;
 known bigint; complete bigint := 0; rate provider_cost_rates%ROWTYPE; estimate bigint; payload jsonb;
BEGIN
 IF current_setting('folio.importing',true)='on' THEN RETURN NEW; END IF;
 IF TG_TABLE_NAME='keyword_benchmark_runs' THEN
   IF TG_OP='UPDATE' AND NEW.usage_json IS NOT DISTINCT FROM OLD.usage_json AND NEW.status IS NOT DISTINCT FROM OLD.status THEN RETURN NEW; END IF;
   src:='keyword'; rev:=NEW.revision; prov:='openai'; mdl:=NEW.model; stat:=NEW.status;
   payload:=NEW.usage_json::jsonb;
   IF jsonb_typeof(payload->'inputTokens')='number' AND (payload->>'inputTokens') ~ '^[0-9]{1,13}$' THEN inp:=(payload->>'inputTokens')::bigint; END IF;
   IF jsonb_typeof(payload->'cachedInputTokens')='number' AND (payload->>'cachedInputTokens') ~ '^[0-9]{1,13}$' THEN cached:=(payload->>'cachedInputTokens')::bigint; END IF;
   IF jsonb_typeof(payload->'outputTokens')='number' AND (payload->>'outputTokens') ~ '^[0-9]{1,13}$' THEN outp:=(payload->>'outputTokens')::bigint; END IF;
 ELSIF TG_TABLE_NAME='evaluation_runs' THEN
   IF NEW.mode <> 'live' OR NEW.deleted_at IS NOT NULL THEN RETURN NEW; END IF;
   IF TG_OP='UPDATE' AND (NEW.result_json::jsonb->'usage') IS NOT DISTINCT FROM (OLD.result_json::jsonb->'usage')
     AND NEW.status IS NOT DISTINCT FROM OLD.status THEN RETURN NEW; END IF;
   src:='evaluation'; rev:=NEW.revision; prov:='openai'; payload:=NEW.result_json::jsonb; mdl:=payload->>'model'; stat:=NEW.status;
   IF (payload#>>'{usage,input_tokens}') ~ '^[0-9]{1,13}$' THEN inp:=(payload#>>'{usage,input_tokens}')::bigint; END IF;
   IF (payload#>>'{usage,input_tokens_details,cached_tokens}') ~ '^[0-9]{1,13}$' THEN cached:=(payload#>>'{usage,input_tokens_details,cached_tokens}')::bigint; END IF;
   IF (payload#>>'{usage,output_tokens}') ~ '^[0-9]{1,13}$' THEN outp:=(payload#>>'{usage,output_tokens}')::bigint; END IF;
 ELSE
   IF TG_OP='UPDATE' AND NEW.result_json IS NOT DISTINCT FROM OLD.result_json THEN RETURN NEW; END IF;
   src:='seo'; rev:=coalesce(NEW.retrieved_at,0); prov:='dataforseo'; payload:=NEW.result_json::jsonb;
   stat:=coalesce(payload->>'status','unconfirmed');
   IF (payload->>'totalCostUsd') ~ '^[0-9]+(\.[0-9]+)?$' AND (payload->>'totalCostUsd')::numeric <= 1000000 THEN
     known:=round((payload->>'totalCostUsd')::numeric*1000000)::bigint;
     IF payload->>'costIsComplete' IN ('true','1') THEN complete:=1; END IF;
   ELSIF (payload->>'knownCostUsd') ~ '^[0-9]+(\.[0-9]+)?$' AND (payload->>'knownCostUsd')::numeric <= 1000000
      AND (jsonb_typeof(payload#>'{organic,costUsd}')='number' OR jsonb_typeof(payload#>'{backlinks,costUsd}')='number') THEN
     known:=round((payload->>'knownCostUsd')::numeric*1000000)::bigint;
   END IF;
 END IF;
 IF inp > 1000000000000 OR cached > 1000000000000 OR outp > 1000000000000 THEN inp:=NULL; cached:=NULL; outp:=NULL; END IF;
 SELECT * INTO rate FROM provider_cost_rates WHERE model=mdl;
 IF inp IS NOT NULL AND outp IS NOT NULL AND rate.model IS NOT NULL AND (cached IS NULL OR cached<=inp) THEN
   estimate:=round((inp-coalesce(cached,0))*rate.input_usd_per_million::numeric + coalesce(cached,0)*rate.cached_usd_per_million::numeric + outp*rate.output_usd_per_million::numeric)::bigint;
 END IF;
 INSERT INTO provider_cost_observations(user_id,source,source_id,source_revision,provider,model,status,source_created_at,observed_at,
 input_tokens,cached_input_tokens,output_tokens,estimated_token_micros,reported_known_micros,reported_complete,rate_version)
 VALUES(NEW.user_id,src,NEW.id,rev,prov,mdl,stat,NEW.created_at,(extract(epoch from clock_timestamp())*1000)::bigint,
 inp,cached,outp,estimate,known,complete,rate.version) ON CONFLICT DO NOTHING;
 RETURN NEW;
END $$;
CREATE TRIGGER cost_keyword_insert AFTER INSERT ON keyword_benchmark_runs FOR EACH ROW EXECUTE FUNCTION folio_cost_snapshot();
CREATE TRIGGER cost_keyword_update AFTER UPDATE ON keyword_benchmark_runs FOR EACH ROW EXECUTE FUNCTION folio_cost_snapshot();
CREATE TRIGGER cost_evaluation_insert AFTER INSERT ON evaluation_runs FOR EACH ROW EXECUTE FUNCTION folio_cost_snapshot();
CREATE TRIGGER cost_evaluation_update AFTER UPDATE ON evaluation_runs FOR EACH ROW EXECUTE FUNCTION folio_cost_snapshot();
CREATE TRIGGER cost_seo_insert AFTER INSERT ON seo_reports FOR EACH ROW EXECUTE FUNCTION folio_cost_snapshot();
CREATE TRIGGER cost_seo_update AFTER UPDATE ON seo_reports FOR EACH ROW EXECUTE FUNCTION folio_cost_snapshot();

